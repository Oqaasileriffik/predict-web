let C = /[bcdfghjklmnŋ\ue000pqrstvwxzBCDFGHJKLMNPQRSTVWXZ]/ui;
let V = /[aeiouyæøåAEIOYÆØÅ]/ui;

function lower(str) {
	return str.toLowerCase();
}

function build_word(dms) {
	let rv = dms[0];
	for (let i=1 ; i<dms.length ; ++i) {
		let dm = lower(dms[i]);

		if (C.test(rv.charAt(rv.length-1)) && C.test(dm.charAt(0)) && C.test(dm.charAt(1))) {
			rv = rv.substring(0, rv.length - 1);
		}
		else if (sandhi.hasOwnProperty(dm)) {
			let s = sandhi[dm];
			if (s === 'tru') {
				if (C.test(rv.charAt(rv.length-1))) {
					rv = rv.substring(0, rv.length - 1);
				}
			}
		}
		rv += dm.substring(0, dm.length - 3);
	}
	return rv;
}

